-- 5) 메뉴 Action 테이블 (seed V2.2에는 없었음. 이미 있으면 건너뜀)
CREATE TABLE IF NOT EXISTS `ju_menu_action` (
  `ACT_ID` bigint(20) NOT NULL AUTO_INCREMENT COMMENT 'Action ID',
  `MNU_ID` bigint(20) NOT NULL COMMENT '메뉴 ID',
  `ACT_CD` varchar(20) NOT NULL COMMENT 'Action 코드',
  `ACT_KIND` varchar(8) NOT NULL COMMENT 'Action 종류(MACT)',
  `HANDLER_ID` varchar(100) NOT NULL COMMENT 'Action Handler ID',
  `USE_YN` varchar(8) NOT NULL DEFAULT 'YENO0001' COMMENT '사용여부',
  `ENABLED_YN` varchar(8) NOT NULL DEFAULT 'YENO0001' COMMENT '활성여부',
  `SORT_ORD` int(11) NOT NULL DEFAULT 0 COMMENT '정렬순서',
  PRIMARY KEY (`ACT_ID`),
  UNIQUE KEY `UK_JU_MENU_ACTION_01` (`MNU_ID`,`ACT_CD`),
  CONSTRAINT `FK_JU_MENU_ACTION_01` FOREIGN KEY (`MNU_ID`) REFERENCES `ju_menu` (`MNU_ID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='메뉴 Action';

CREATE TABLE IF NOT EXISTS `ju_menu_action_detail` (
  `ACT_ID` bigint(20) NOT NULL COMMENT 'Action ID',
  `ACT_NM` varchar(100) DEFAULT NULL COMMENT 'Action명',
  `ACT_DESC` varchar(500) DEFAULT NULL COMMENT 'Action 설명',
  `ACT_NM_KEY` varchar(200) DEFAULT NULL COMMENT 'Action명 다국어 Resource Key',
  `ACT_DESC_KEY` varchar(200) DEFAULT NULL COMMENT 'Action설명 다국어 Resource Key',
  PRIMARY KEY (`ACT_ID`),
  CONSTRAINT `FK_JU_MENU_ACTION_DETAIL_01` FOREIGN KEY (`ACT_ID`) REFERENCES `ju_menu_action` (`ACT_ID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='메뉴 Action 상세정보';

